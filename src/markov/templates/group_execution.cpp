GroupExecution GroupExecution::declaration(const nlohmann::json & source) {
    GroupExecution result;
    result.group_ = source.at("group").get<std::string>();
    result.field_ = source.at("field").get<std::string>();
    result.fan_in_ = source.at("fan_in").get<std::int64_t>();
    if (result.fan_in_ < 2) throw std::invalid_argument("group reduction needs a fan-in of at least two");
    return result;
}

std::vector<GroupExecution::Part> GroupExecution::parts(std::span<const Parameters> members) const {
    std::vector<Parameters> current;
    for (const auto & member : members) {
        if (member.at(field_) > 0) current.push_back(member);
    }

    std::vector<Part> result;
    while (current.size() > 1) {
        std::vector<Parameters> next;
        for (std::size_t begin = 0; begin < current.size();) {
            const auto count = std::min(current.size() - begin, static_cast<std::size_t>(fan_in_));
            const auto inputs = std::span(current).subspan(begin, count);
            auto output = inputs.front();
            std::int64_t extent = 0;
            for (const auto & input : inputs) {
                if (__builtin_add_overflow(extent, input.at(field_), &extent)) throw std::overflow_error("group reduction extent overflows");
            }
            output[field_] = extent;
            if (count > 1)
                result.push_back({
                    { inputs.begin(), inputs.end() },
                    output
                });
            next.push_back(std::move(output));
            begin += count;
        }
        current = std::move(next);
    }
    return result;
}

GroupExecution GroupExecution::compile(const nlohmann::json & source, nlohmann::json & pattern, std::span<const Parameters> members) {
    auto result = declaration(source);
    if (!pattern.at("requirements").empty() || !pattern.at("signals").empty() || !pattern.at("communication").is_null())
        throw std::invalid_argument("group launch body has external synchronization");

    std::vector<std::array<std::size_t, 3>> bodies;
    const auto & nodes = pattern.at("nodes");
    for (std::size_t device = 0; device < nodes.size(); ++device) {
        if (nodes[device].at("kind") != "device") continue;

        std::vector<std::size_t> submissions;
        for (const auto & link : pattern.at("links")) {
            if (link.at("target") == device && link.at("kind") == "submission") submissions.push_back(link.at("source").get<std::size_t>());
        }
        if (submissions.size() != 1) throw std::invalid_argument("group launch needs one native submitter");
        const auto submit = submissions.front();
        const auto resource = nodes.at(submit).at("resource").get<std::size_t>();
        const auto sequence = pattern.at("sequences").at(resource).get<std::vector<std::size_t>>();
        const auto position = std::ranges::find(sequence, submit);
        if (position == sequence.begin() || position == sequence.end()) throw std::invalid_argument("group launch has no preceding host service");
        const auto host = *std::prev(position);
        if (nodes.at(host).at("kind") != "host" || nodes.at(submit).at("kind") != "submit")
            throw std::invalid_argument("group launch has an incompatible host body");
        bodies.push_back({ host, submit, device });
    }
    if (bodies.empty() || bodies.size() != result.parts(members).size()) throw std::invalid_argument("observed launches disagree with group reduction");

    // Profiler node identities need not follow the native worker's submission order.
    const auto worker = nodes.at(bodies.front()[1]).at("resource").get<std::size_t>();
    const auto worker_sequence = pattern.at("sequences").at(worker).get<std::vector<std::size_t>>();
    std::ranges::sort(bodies, [&worker_sequence](const auto & left, const auto & right) {
        return std::ranges::find(worker_sequence, left[1]) < std::ranges::find(worker_sequence, right[1]);
    });

    std::set<std::size_t> removed;
    for (std::size_t index = 1; index < bodies.size(); ++index) {
        for (std::size_t slot = 0; slot < bodies[index].size(); ++slot) {
            if (nodes.at(bodies[index][slot]) != nodes.at(bodies.front()[slot]))
                throw std::invalid_argument("group reduction has unequal native launch bodies");
            removed.insert(bodies[index][slot]);
        }
    }

    // Keep one launch body and the caller/worker boundaries; source repetitions are regenerated by the same rule.
    std::vector<std::size_t> remapped(nodes.size());
    auto retained = nlohmann::json::array();
    for (std::size_t node = 0; node < nodes.size(); ++node) {
        if (!removed.contains(node)) {
            remapped[node] = retained.size();
            retained.push_back(nodes[node]);
        }
    }
    auto links = nlohmann::json::array();
    for (auto link : pattern.at("links")) {
        const auto from = link.at("source").get<std::size_t>();
        const auto to = link.at("target").get<std::size_t>();
        if (removed.contains(from) || removed.contains(to)) {
            if (removed.contains(from) != removed.contains(to)) throw std::invalid_argument("group body has an external dependency");
            continue;
        }
        link["source"] = remapped[from];
        link["target"] = remapped[to];
        links.push_back(std::move(link));
    }
    for (auto & sequence : pattern["sequences"]) {
        auto filtered = nlohmann::json::array();
        for (const auto & node : sequence) {
            const auto identity = node.get<std::size_t>();
            if (!removed.contains(identity)) filtered.push_back(remapped[identity]);
        }
        sequence = std::move(filtered);
    }
    auto & call = pattern["host_call"];
    if (!call.is_null()) {
        for (auto & node : call) {
            const auto identity = node.get<std::size_t>();
            if (removed.contains(identity)) throw std::invalid_argument("group body owns an outer host port");
            node = remapped[identity];
        }
    }
    for (std::size_t slot = 0; slot < result.body_.size(); ++slot) result.body_[slot] = remapped[bodies.front()[slot]];
    pattern["nodes"] = std::move(retained);
    pattern["links"] = std::move(links);
    result.validate(ExecutionPattern::read(pattern));
    return result;
}

GroupExecution GroupExecution::read(const nlohmann::json & source) {
    auto result = declaration(source);
    result.body_ = source.at("body").get<std::array<std::size_t, 3>>();
    return result;
}

void GroupExecution::validate(const ExecutionPattern & pattern) const {
    if (pattern.steps.at(body_[0]).kind != ExecutionKind::Host || pattern.steps.at(body_[1]).kind != ExecutionKind::Submit
        || pattern.steps.at(body_[2]).kind != ExecutionKind::Device || !pattern.requirements.empty() || !pattern.signals.empty() || pattern.communication)
        throw std::invalid_argument("invalid group launch body");
    for (const auto & sequence : pattern.sequences) {
        std::vector<std::size_t> positions;
        for (std::size_t index = 0; index < sequence.size(); ++index) {
            if (std::ranges::find(body_, sequence[index]) != body_.end()) positions.push_back(index);
        }
        if (!positions.empty() && positions.back() - positions.front() + 1 != positions.size())
            throw std::invalid_argument("group body is not contiguous on its execution resource");
    }
    for (const auto & link : pattern.links) {
        const bool from = std::ranges::find(body_, link.source) != body_.end();
        const bool to = std::ranges::find(body_, link.target) != body_.end();
        if (from && !to) throw std::invalid_argument("group body has an outgoing dependency");
    }
}

GroupExecutionPlan GroupExecution::instantiate(const ExecutionPattern & pattern, const InputGroup & group, const Parameters & parameters,
                                               std::span<const Parameters> members) const {
    const auto work = parts(members);
    if (work.empty()) throw std::invalid_argument("group reduction requires a multi-member implementation");
    GroupExecutionPlan result{ pattern, nlohmann::json::array() };
    std::vector<std::array<std::size_t, 3>> bodies{ body_ };
    for (std::size_t part = 0; part < work.size(); ++part) {
        if (part != 0) {
            std::array<std::size_t, 3> body;
            for (std::size_t slot = 0; slot < body.size(); ++slot) {
                body[slot] = result.pattern.steps.size();
                result.pattern.steps.push_back(pattern.steps.at(body_[slot]));
            }
            bodies.push_back(body);
        }
        for (const auto node : bodies[part]) result.pattern.steps[node].part = part;
        auto inputs = nlohmann::json::array();
        for (const auto & member : work[part].inputs) inputs.push_back(group.dimensions(parameters, member));
        result.parts.push_back({
            { "inputs", std::move(inputs) },
            { "output", group.dimensions(parameters, work[part].output) },
            { "dtype", group.dtype }
        });
    }

    // Repeat only the verified internal links; the incoming caller edge belongs to the first iteration.
    for (std::size_t part = 1; part < bodies.size(); ++part) {
        for (const auto & link : pattern.links) {
            const auto from = std::ranges::find(body_, link.source);
            const auto to = std::ranges::find(body_, link.target);
            if (from != body_.end() && to != body_.end())
                result.pattern.links.push_back(
                    { bodies[part][static_cast<std::size_t>(from - body_.begin())], bodies[part][static_cast<std::size_t>(to - body_.begin())], link.kind });
        }
    }
    for (std::size_t resource = 0; resource < pattern.sequences.size(); ++resource) {
        const auto & source = pattern.sequences[resource];
        auto & sequence = result.pattern.sequences[resource];
        sequence.clear();
        bool inserted = false;
        for (const auto node : source) {
            if (std::ranges::find(body_, node) == body_.end()) sequence.push_back(node);
            else if (!inserted) {
                for (const auto & body : bodies) {
                    for (const auto original : source) {
                        const auto slot = std::ranges::find(body_, original);
                        if (slot != body_.end()) sequence.push_back(body[static_cast<std::size_t>(slot - body_.begin())]);
                    }
                }
                inserted = true;
            }
        }
    }
    return result;
}

const std::string & GroupExecution::group() const { return group_; }

nlohmann::json GroupExecution::document() const {
    return {
        {  "group",  group_ },
        {  "field",  field_ },
        { "fan_in", fan_in_ },
        {   "body",   body_ }
    };
}

